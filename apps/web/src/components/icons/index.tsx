import * as React from 'react';

type IconProps = React.SVGProps<SVGSVGElement> & { size?: number };

function createIcon(paths: React.ReactNode) {
  const Icon = React.forwardRef<SVGSVGElement, IconProps>(({ size = 18, ...props }, ref) => (
    <svg
      ref={ref}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.5"
      strokeLinecap="round"
      strokeLinejoin="round"
      {...props}
    >
      {paths}
    </svg>
  ));
  Icon.displayName = 'Icon';
  return Icon;
}

