import { sql } from 'drizzle-orm';
import {
  bigint,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from 'drizzle-orm/pg-core';

import { scans } from './scans';

/**
 * `scan_events` — append-only progress stream for one scan (Sprint 2, SP-1/SP-3).
 *
 * The browser watches a scan through a short-poll SSE endpoint; this table is
 * what it polls. Rows are only ever inserted — the web app is the sole writer
 * (TB2), and the worker's incremental callbacks are the only source.
 *
 * ## `id` is a bigint IDENTITY, not a uuid — a deliberate deviation (D2)
 *
 * Every other table uses `uuid` to avoid a sequential-enumeration vector. That
 * argument does not apply here: the id is never a public URL and never accepted
 * as input. What the stream needs is a **monotonic cursor** for polling
 * (`WHERE scan_id = ? AND id > cursor ORDER BY id LIMIT 100`), and an identity
 * column provides exactly that with no clock-skew ambiguity. `created_at` remains
 * the authoritative time; `id` is the authoritative order.
 *
 * ## Idempotency
 *
 * `UNIQUE (scan_id, seq)` with `seq` emitted by the worker means a retried
 * callback re-inserts the same `seq` and is absorbed by `ON CONFLICT DO NOTHING`
 * — retries cannot duplicate the feed.
 *
 * ## `type` vocabulary (closed set, documented here rather than as an enum)
 *
 * `scan.started`, `scan.completed`, `scan.failed`, `check.started`,
 * `check.completed`, `scan.progress`. A `text` column, because the set is small,
 * evolving, and never used as a lookup key; a bad value is a review miss, not a
 * corrupt row.
 */
export const scanEvents = pgTable(
  'scan_events',
  {
    /** Monotonic SSE cursor. Identity, never generated by the application. */
    id: bigint('id', { mode: 'number' }).generatedAlwaysAsIdentity().primaryKey(),

    /** The scan this event belongs to. Cascades with the scan. */
    scanId: uuid('scan_id')
      .notNull()
      .references(() => scans.id, { onDelete: 'cascade' }),

    /** Worker-assigned, per-scan, monotonic sequence number. Half of the dedup key. */
    seq: integer('seq').notNull(),

    /** One of the closed vocabulary above. */
    type: text('type').notNull(),

    /** Event-specific data. NOT NULL `{}` so a reader never handles a null payload. */
    payload: jsonb('payload')
      .notNull()
      .default(sql`'{}'::jsonb`),

    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => ({
    /**
     * Worker-callback idempotency (D2): a repeated `(scan_id, seq)` is rejected
     * by the database, so `ON CONFLICT DO NOTHING` makes callback retries safe.
     */
    scanSeqUnique: unique('scan_events_scan_seq_unique').on(table.scanId, table.seq),

    /**
     * The SSE poll path — `scan_id` + ascending `id` cursor. This is the index
     * that keeps a 1 s poll cheap for the lifetime of a long scan.
     */
    pollIdx: index('scan_events_poll_idx').on(table.scanId, table.id),

    /**
     * Time ordering across all scans. Sprint 2 has no TTL, but this is the index
     * a future retention sweep would need — created now, while the table is
     * small, so the sweep never requires a production `CREATE INDEX`.
     */
    createdAtIdx: index('scan_events_created_at_idx').on(table.createdAt),
  }),
);

export type ScanEvent = typeof scanEvents.$inferSelect;
export type NewScanEvent = typeof scanEvents.$inferInsert;
